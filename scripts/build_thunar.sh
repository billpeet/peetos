#!/usr/bin/env bash
set -euo pipefail

# Build the Thunar file manager for PeetOS (musl, shared, GTK 3 Wayland) into
# the staged sysroot (wayland/out/stage), on top of scripts/build_gtk.sh:
#   libxfce4util, xfconf (library; its daemon needs D-Bus), libxfce4ui
#   (Wayland only, with libxfce4kbd-private), exo and Thunar (autotools),
#   plus the data a file manager needs: a shared-mime-info database (built
#   with the build machine's update-mime-database) and the AdwaitaLegacy PNG
#   icon theme (there is no SVG loader).
#
# Build-machine tools: msgfmt (gettext; Xfce merges .desktop files with it
# even without NLS), gdbus-codegen and update-mime-database. See docs/thunar.md.

ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
WL="${ROOT_DIR}/wayland"
OUT="${WL}/out"
STAGE="${OUT}/stage"
BUILD="${OUT}/build/thunar"
PATCHES="${WL}/peetos/patches"
MUSL_CC="${MUSL_CC:-${ROOT_DIR}/musl/sysroot/bin/musl-gcc}"
MUSL_SHARED_LIB="${ROOT_DIR}/musl/shared/lib"
JOBS="${JOBS:-$(nproc 2>/dev/null || echo 2)}"

for tool in pkg-config msgfmt gdbus-codegen update-mime-database patch; do
  command -v "${tool}" >/dev/null 2>&1 || { echo "${tool} not found on the build machine (see docs/thunar.md)" >&2; exit 1; }
done
if [[ ! -f "${STAGE}/usr/lib/libgtk-3.so.0" ]]; then
  echo "GTK 3 not staged (run scripts/build_gtk.sh first)" >&2
  exit 1
fi
for d in libxfce4util xfconf libxfce4ui exo thunar adwaita-icon-theme-legacy shared-mime-info; do
  [[ -d "${WL}/${d}-src" ]] || { echo "${d} source not found (run 'make -C wayland fetch')" >&2; exit 1; }
done

rm -rf "${BUILD}"
mkdir -p "${BUILD}/tools"

run_logged() {
  local log="$1"
  shift
  "$@" > "${log}" 2>&1 || { tail -40 "${log}" >&2; exit 1; }
}

# The target GLib is 2.82; keep the build machine's (newer) gdbus-codegen from
# emitting code that needs later GLib APIs.
cat > "${BUILD}/tools/gdbus-codegen" <<EOF
#!/bin/sh
exec $(command -v gdbus-codegen) --glib-max-allowed 2.82 "\$@"
EOF
chmod +x "${BUILD}/tools/gdbus-codegen"
export PATH="${BUILD}/tools:${PATH}"

# Code generated by the build machine's gdbus-codegen guards newer GLib APIs
# with "#if GLIB_VERSION_MAX_ALLOWED >= GLIB_VERSION_2_84"; the target GLib
# (2.82) does not define the newer version macros, which then evaluate to 0
# and select the newer API. Define them so those guards work.
cat > "${BUILD}/tools/glib-newer-versions.h" <<'HDR'
/* See build_thunar.sh: version macros newer than the target GLib, so code
 * from the build machine's gdbus-codegen picks the 2.82-compatible paths. */
#define GLIB_VERSION_2_84 (G_ENCODE_VERSION (2, 84))
#define GLIB_VERSION_2_86 (G_ENCODE_VERSION (2, 86))
#define GLIB_VERSION_2_88 (G_ENCODE_VERSION (2, 88))
HDR
GLIB_NEWER_VERSIONS="-include ${BUILD}/tools/glib-newer-versions.h"
TARGET_CFLAGS="-O2 -fPIC"
TARGET_LDFLAGS="-L${MUSL_SHARED_LIB} -L${STAGE}/usr/lib -Wl,-rpath-link,${STAGE}/usr/lib -Wl,-z,max-page-size=0x1000"

# Configure and build an autotools package from a pristine copy of its
# source (patches from wayland/peetos/patches/<name>-*.patch are applied to
# the copy), installing into the stage.
autotools_build() {
  local name="$1" src="$2"
  shift 2
  echo "[thunar] building ${name}"
  cp -a "${src}" "${BUILD}/${name}"
  local p
  for p in "${PATCHES}/${name}"-*.patch; do
    [[ -f "${p}" ]] || continue
    patch -d "${BUILD}/${name}" -p1 < "${p}" > "${BUILD}/${name}.patch.log" 2>&1 \
      || { cat "${BUILD}/${name}.patch.log" >&2; exit 1; }
  done
  (
    cd "${BUILD}/${name}"
    run_logged configure.log env CC="${MUSL_CC}" CFLAGS="${TARGET_CFLAGS}" \
      CPPFLAGS="-isystem ${STAGE}/usr/include ${GLIB_NEWER_VERSIONS}" LDFLAGS="${TARGET_LDFLAGS}" \
      PKG_CONFIG_LIBDIR="${STAGE}/usr/lib/pkgconfig:${STAGE}/usr/share/pkgconfig" \
      PKG_CONFIG_SYSROOT_DIR="${STAGE}" GDBUS_CODEGEN="${BUILD}/tools/gdbus-codegen" \
      ./configure --build="$(cc -dumpmachine)" --host=x86_64-linux-musl \
      --prefix=/usr --sysconfdir=/etc --localstatedir=/var \
      --enable-shared --disable-static --disable-nls --disable-gtk-doc --disable-debug "$@"
    run_logged make.log make -j"${JOBS}" GDBUS_CODEGEN="${BUILD}/tools/gdbus-codegen"
    run_logged install.log make install DESTDIR="${STAGE}"
  )
  rm -f "${STAGE}"/usr/lib/*.la
}

# Xfce 4.20 release tarballs are autotools dists (their meson files are
# incomplete), so everything below uses configure.
autotools_build libxfce4util "${WL}/libxfce4util-src" --disable-introspection --disable-vala
autotools_build xfconf "${WL}/xfconf-src" --disable-introspection --disable-vala --disable-gsettings-backend
autotools_build libxfce4ui "${WL}/libxfce4ui-src" \
  --disable-x11 --enable-wayland --disable-libsm --disable-startup-notification --disable-glibtop \
  --disable-gladeui2 --disable-gudev --disable-epoxy --disable-introspection --disable-vala --disable-tests \
  --with-vendor-info=PeetOS
autotools_build exo "${WL}/exo-src"
# Thunar's configure insists on libX11. Naming X include/library directories
# makes AC_PATH_X accept them without probing; the libX11 link test then just
# fails, HAVE_LIBX11 stays undefined, and the X11 code is not built.
autotools_build thunar "${WL}/thunar-src" \
  --x-includes="${STAGE}/usr/include" --x-libraries="${STAGE}/usr/lib" \
  --disable-gudev --disable-notifications --disable-exif --disable-pcre2 --disable-wallpaper-plugin \
  --disable-introspection

# --- data: MIME database, icon theme, GTK settings -----------------------------------
echo "[thunar] building the MIME database"
mkdir -p "${STAGE}/usr/share/mime/packages"
cp "${WL}/shared-mime-info-src/data/freedesktop.org.xml.in" "${STAGE}/usr/share/mime/packages/freedesktop.org.xml"
run_logged "${BUILD}/mime.log" update-mime-database -n "${STAGE}/usr/share/mime"

echo "[thunar] staging the AdwaitaLegacy icon theme"
rm -rf "${STAGE}/usr/share/icons/AdwaitaLegacy"
cp -a "${WL}/adwaita-icon-theme-legacy-src/AdwaitaLegacy" "${STAGE}/usr/share/icons/"
mkdir -p "${STAGE}/etc/gtk-3.0"
cat > "${STAGE}/etc/gtk-3.0/settings.ini" <<'EOF'
[Settings]
gtk-icon-theme-name = AdwaitaLegacy
gtk-font-name = DejaVu Sans 10
EOF

echo "[thunar] staged: $(cd "${STAGE}/usr/lib" && ls | grep -E '^lib(xfce4util|xfconf-0|xfce4ui-2|xfce4kbd-private-3|exo-2|thunarx-3)\.so\.[0-9]+$' | tr '\n' ' ') thunar=$( [[ -x ${STAGE}/usr/bin/thunar ]] && echo yes || echo no)"
